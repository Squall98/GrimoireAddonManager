T.test("mémoire : alerte au-delà du seuil, une seule fois par période", function(B)
	local ns = B.demarrer({ locale = "frFR" })
	ns.Reglages.ecrire("erreurs.memoire_seuil_addon", 10)
	ns.Reglages.ecrire("erreurs.memoire_seuil_total", 100)
	B.memoire.Baganator = 40 * 1024
	B.memoire.Curator = 1024
	B.avancer(61)
	T.vrai(B.chat_contient("Baganator utilise 40.0 Mo de mémoire (seuil 10.0 Mo)"), table.concat(tous(B), "\n"))
