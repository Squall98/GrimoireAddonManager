T.test("fenêtre : filtre par add-on, pages, effacer", function(B)
	local ns = B.demarrer({ locale = "frFR" })
	ns.Reglages.ecrire("erreurs.annonce", "rien")
	ns.Reglages.ecrire("erreurs.lignes_liste", 5)
	for i = 1, 12 do B.erreur_jeu("Interface/AddOns/Mod" .. (i % 2) .. "/f.lua:" .. i .. ": e" .. i) end
	local W = ns.ErreursFenetre
	W.ouvrir()
	T.vrai(W.pageTexte:GetText():find("1 / 3", 1, true), W.pageTexte:GetText())
	W.boutonSuivant._scripts.OnClick()
	T.vrai(W.pageTexte:GetText():find("2 / 3", 1, true))
	W.filtreSuivant()
	T.vrai(W.boutonFiltre.etiquette:GetText():find("Add-on : Mod", 1, true), W.boutonFiltre.etiquette:GetText())
	T.vrai(W.pageTexte:GetText():find("1 / 2", 1, true))
	local avant = ns.Erreurs.nombreDifferentes()
	W.effacer()
	T.eq(ns.Erreurs.nombreDifferentes(), avant - 6, "seul le filtre est effacé")
	W.boutonEffacer._scripts.OnClick()
	T.eq(ns.Erreurs.nombreDifferentes(), 0)
	T.vrai(W.resume:GetText():find("Aucune erreur", 1, true))
end)

