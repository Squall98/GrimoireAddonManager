T.test("fenêtre en français : liste, détail complet et copie", function(B)
	local ns = B.demarrer({ locale = "frFR" })
	ns.Reglages.ecrire("erreurs.annonce", "rien")
	B.erreur_jeu(CHEMIN)
	B.erreur_jeu(CHEMIN)
	B.erreur_jeu("Interface/AddOns/BarAddon/V.lua:3: autre souci")
	local W = ns.ErreursFenetre
	W.ouvrir()
	T.vrai(W.estOuverte())
	T.vrai(W.resume:GetText():find("2 erreurs différentes, 3 au total, 2 add-ons", 1, true), W.resume:GetText())
	T.vrai(W.lignes[1].texte:GetText():find("BarAddon", 1, true), "la plus récente en premier")
	T.vrai(W.lignes[2].texte:GetText():find("(x2)", 1, true), "les répétitions sont visibles")
	W.choisir(W.lignes[2].erreur.id)
	local d = W.detail:GetText()
	for _, morceau in ipairs({ "Add-on : FooAddon", "Fichier : Core/Machin.lua", "Ligne : 42", "Répétitions : 2",
		"Première fois :", "Dernière fois :", "En combat : non", "Pile d'appels", "attempt to index" }) do
		T.vrai(d:find(morceau, 1, true), "détail : " .. morceau .. "\n" .. d)
	end
	W.copier(false)
	T.eq(W.dernierCopie, d, "le texte prêt à coller est l'erreur complète")
	W.copier(true)
	T.vrai(W.dernierCopie:find("BarAddon", 1, true) and W.dernierCopie:find("FooAddon", 1, true), "copier tout")
end)

