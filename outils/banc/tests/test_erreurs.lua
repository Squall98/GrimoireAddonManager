-- B4-01 : capture et journal des erreurs, fenêtre d'erreurs, mémoire et mesure du processeur.
local T = dofile((os.getenv("MAA_RACINE") or ".") .. "/outils/banc/test.lua")

local CHEMIN = "Interface/AddOns/FooAddon/Core/Machin.lua:42: attempt to index a nil value"

local function tous(B) return B.chat_texte() end

T.test("une erreur est attribuée à son add-on, comptée et détaillée", function(B)
	local ns = B.demarrer({ locale = "frFR" })
	B.erreur_jeu(CHEMIN)
	local liste = ns.Erreurs.liste()
	T.eq(#liste, 1)
	local e = liste[1]
	T.eq(e.addon, "FooAddon")
	T.eq(e.fichier, "Core/Machin.lua")
	T.eq(e.ligne, 42)
	T.eq(e.n, 1)
	T.vrai(e.message:find("attempt to index", 1, true), "message gardé")
	T.vrai(#e.pile > 0, "pile d'appels gardée")
	T.eq(e.premiere, e.derniere)
	T.eq(ns.Erreurs.nombre("FooAddon"), 1)
	T.eq(ns.Erreurs.dansLaSession("FooAddon"), 1)
end)

T.test("le gestionnaire d'origine reçoit toujours l'erreur (BugSack, fenêtre du jeu)", function(B)
	B.demarrer()
