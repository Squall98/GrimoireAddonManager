	T.eq(#B.erreurs_jeu, avant + 1)
	T.vrai(B.erreurs_jeu[#B.erreurs_jeu]:find("FooAddon", 1, true))
end)

T.test("les répétitions se regroupent avec première et dernière date", function(B)
	local ns = B.demarrer()
	B.erreur_jeu(CHEMIN)
	B.avancer(90)
	for _ = 1, 4 do B.erreur_jeu(CHEMIN) end
