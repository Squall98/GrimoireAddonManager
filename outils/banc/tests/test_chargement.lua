-- Le banc charge l'add-on sans erreur et l'API imitée est fidèle à ce qu'on sait du jeu.
local T = dofile((os.getenv("MAA_RACINE") or ".") .. "/outils/banc/test.lua")

T.test("l'add-on se charge sans erreur", function(B)
	local ns = B.demarrer()
	T.sans_erreur()
	T.vrai(ns.Reglages and ns.Journal and ns.Commandes and ns.Fiches and ns.Langue, "modules présents")
	T.vrai(B.charge.GrimoireAddonManager, "marqué chargé")
	T.eq(#B.xml_ignores, 0, "aucun fichier xml ignoré")
end)

T.test("le fichier toc est suivi dans l'ordre et les sauvegardes sont déclarées", function(B)
	B.demarrer()
	T.eq(B.sv_compte[1], "MesAddonsDB")
	T.eq(B.sv_perso[1], "MesAddonsPersoDB")
	T.vrai(MesAddonsDB and MesAddonsDB.reglages, "variable du compte créée")
	T.vrai(MesAddonsPersoDB, "variable du personnage créée")
end)

T.test("C_AddOns imite le jeu : liste des vrais .toc, plusieurs valeurs, état par perso", function(B)
	B.demarrer()
	local n = C_AddOns.GetNumAddOns()
	T.vrai(n >= 90, "au moins 90 add-ons dans la liste (obtenu " .. n .. ")")
	local nom, titre, notes, chargeable, raison = C_AddOns.GetAddOnInfo("Auctionator")
	T.eq(nom, "Auctionator")
	T.eq(titre, "Auctionator")
	T.eq(raison, "", "activé = raison vide")
	T.eq(C_AddOns.GetAddOnEnableState("Auctionator"), 2)
	C_AddOns.DisableAddOn("Auctionator")
	T.eq(C_AddOns.GetAddOnEnableState("Auctionator"), 0)
	local _, _, _, _, raison2 = C_AddOns.GetAddOnInfo("Auctionator")
	T.eq(raison2, "DISABLED")
	T.eq(C_AddOns.GetAddOnMetadata("GrimoireAddonManager", "Version"), "1.1.2")
	T.eq(C_AddOns.GetAddOnMetadata("Introuvable", "Version"), nil)
	T.vrai(C_AddOns.IsAddOnLoaded("GrimoireAddonManager"))
	T.faux(C_AddOns.IsAddOnLoaded("Auctionator"))
end)

T.test("le jeu simulé connaît /ma (commande prise)", function(B)
	B.demarrer()
	T.eq(SLASH_MAINASSISTON2, "/ma")
	local pris, cle = B.slash("/ma")
	T.vrai(pris); T.eq(cle, "MAINASSISTON")
end)

T.test("les sauvegardes survivent à un rechargement (comme le dossier WTF)", function(B)
	B.demarrer()
	MesAddonsDB.essai = "gardé"
	B.recharger()
	T.eq(MesAddonsDB.essai, "gardé")
end)

T.test("les minuteries avancent avec le temps simulé", function(B)
	B.demarrer()
	local vu = 0
	C_Timer.After(5, function() vu = vu + 1 end)
	B.avancer(4); T.eq(vu, 0)
	B.avancer(2); T.eq(vu, 1)
end)

T.fin()
